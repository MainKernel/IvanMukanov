-- 1. Тривалість блокувань таблиці (Locking & Zero-Downtime):
--    DML-запит UPDATE модифікує рядки й утримує рядкові блокування (ROW EXCLUSIVE),
--    тоді як DDL-команда ALTER TABLE ... SET NOT NULL бере ексклюзивне блокування
--    всієї таблиці (ACCESS EXCLUSIVE), яке блокує навіть звичайні SELECT-запити
--    каталогу. Якщо об'єднати UPDATE та ALTER TABLE в одну транзакцію міграції,
--    ексклюзивне блокування триматиметься значно довше, що зупинить читання каталогу.
-- 2. Сумісність під час поступового розгортання (Rolling Update):
--    Під час деплою старі екземпляри бекенду ще можуть паралельно створювати події
--    без organizerId. Тому спершу випускається код, який завжди записує organizerId,
--    потім окремою міграцією (Фаза 2) заповнюються всі історичні NULL-рядки, і лише
--    після перевірки відсутності NULL виконується фінальне звуження (Фаза 3).
-- 3. Ізоляція збоїв і простота відкату:
--    Зміна даних (DML) та зміна структури (DDL) мають різні ризики. Розділення
--    дозволяє безпечно перевірити стан таблиці між кроками.
-- ============================================================================

